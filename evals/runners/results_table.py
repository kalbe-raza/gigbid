"""Regenerate the B5 results table (and the R&D C table) from result files and splice it into README.md.

    python -m evals.runners.results_table          (prints and updates README between the RESULTS markers)
Every cell comes from a file under evals/results/; '—' means that experiment was not run for that row.
"""

from __future__ import annotations

import json

from agent.settings import ROOT
from evals.runners.common import RESULTS


def load(name: str) -> dict | None:
    f = RESULTS / f"{name}.json"
    return json.loads(f.read_text()) if f.exists() else None


def fmt(x, nd=3, pre="") -> str:
    return "—" if x is None else f"{pre}{x:.{nd}f}"


def rag_table() -> str:
    rag = load("rag_variants") or {"variants": {}}
    outs = {"v0_naive": load("gigsim_outcomes_v0_openb"), "best": load("gigsim_outcomes_best_openb")}
    lines = ["| Variant | Evidence Recall@5 | nDCG@10 | Unsupported claims / proposal (before → after verification) | "
             "Judge score | GigSim reply rate | p95 latency (s) | Cost / proposal (USD) |",
             "|---|---|---|---|---|---|---|---|"]
    for v, label in [("v0_naive", "V0 naive dense"), ("v1_decompose", "V1 decomposition"), ("v2_hybrid", "V2 hybrid"),
                     ("v3_rerank", "V3 rerank"), ("v4_outcome", "V4 outcome-aware"), ("v8_corrective", "V8 corrective"),
                     ("best", "**Shipped (best)**")]:
        r = rag["variants"].get(v, {}).get("overall", {})
        o = (outs.get(v) or {}).get("summary", {})
        unsup = "—" if not o else f"{fmt(o.get('unsupported_claims_per_proposal_before'), 2)} → {fmt(o.get('unsupported_claims_per_proposal_after'), 2)}"
        lines.append(f"| {label} | {fmt(r.get('recall@5'))} | {fmt(r.get('ndcg@10'))} | {unsup} | "
                     f"{fmt(o.get('judge_overall_mean'), 2)} | {fmt(o.get('reply_rate'), 2)} | "
                     f"{fmt(o.get('latency_p95_s'), 1)} | {fmt(o.get('usd_per_proposal'), 4, '$')} |")
    return "\n".join(lines)


def rnd_c_table() -> str:
    d = load("rnd_c_architectures")
    if not d:
        return "_R&D C not run yet._"
    lines = ["| Architecture | Bid/skip accuracy | Unsupported claims / proposal | Violations left in final text | "
             "Violations caught by guard | GigSim reply rate | Tokens / job | p95 latency (s) |", "|---|---|---|---|---|---|---|---|"]
    for k, label in [("react", "(a) single ReAct agent"), ("supervisor", "(b) prebuilt supervisor"), ("graph", "(c) GigBid graph")]:
        s = d["summary"].get(k)
        if s:
            lines.append(f"| {label} | {fmt(s['bid_skip_accuracy'], 2)} | {fmt(s['unsupported_claims_per_proposal'], 2)} | "
                         f"{s['violations_left_in_final_text']} | {s['violations_caught_by_guard']} | "
                         f"{fmt(s['gigsim_reply_rate'], 2)} | {fmt(s['tokens_mean'], 0)} | {fmt(s['latency_p95_s'], 1)} |")
    return "\n".join(lines)


def main() -> None:
    block = ("<!-- RESULTS:START (generated by `python -m evals.runners.results_table`; do not edit by hand) -->\n"
             "### RAG variants (B5)\n\n" + rag_table() + "\n\n### Architectures (R&D C)\n\n" + rnd_c_table() +
             "\n<!-- RESULTS:END -->")
    print(block)
    readme = ROOT / "README.md"
    if readme.exists():
        s = readme.read_text()
        if "<!-- RESULTS:START" in s:
            a, b = s.index("<!-- RESULTS:START"), s.index("<!-- RESULTS:END -->") + len("<!-- RESULTS:END -->")
            readme.write_text(s[:a] + block + s[b:])


if __name__ == "__main__":
    main()
